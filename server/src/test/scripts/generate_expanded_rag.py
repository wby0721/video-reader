def dump(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

def clock(ms):
    return f'{ms//60000:02d}:{ms//1000%60:02d}.{ms%1000:03d}'

def main():
    videos, annotations, counts = [], [], []
    for i, (title, sections, q1, q2, negative) in enumerate(LESSONS):
        ordered_sections = sections[i%4:] + sections[:i%4]
        name, media, user = f'video-{i+1:02d}', 982001+i, 982000
        folder = ROOT / name
        asr, ocr = [], []
        for minute in range(20):
            section, phase = divmod(minute, 5)
            fact = ordered_sections[section]
            first, second = fact.split('。', 1)
            # ASR includes hesitations, self-corrections, occasional wrong homophones,
            # and unrelated speech; annotations refer to source spans, not these artifacts.
            texts = [
                FILLERS[(i+minute)%6] + first + '。' + TEACHING[phase],
                FILLERS[(i+minute+2)%6] + second + '嗯，这里先停一停，再回看刚才的动作。' + ASIDES[(i+minute)%6],
                f'接着说{title}，' + TEACHING[(phase+2)%5] + '这个对找，啊对照，刚才识别成对找了。' + first + '。' + FILLERS[(i+minute+4)%6],
            ]
            for j, text in enumerate(texts):
                bounds = [0, 19000, 41000, 60000]
                asr.append(dict(startMs=minute*60000+bounds[j], endMs=minute*60000+bounds[j+1], text=text))
            for frame in range(6):
                timestamp = minute*60000 + 3000 + frame*9500
                lines = [title, f'课堂记录 第{section+1}部分 第{minute+1}页',
                         first if frame%2 == 0 else second,
                         ['操作前 / 操作后', '变量记录 观察结果', '对照组A 实验组B'][frame%3],
                         OCR_NOISE[(i+minute+frame)%len(OCR_NOISE)],
                         OCR_NOISE[(i+minute+frame+4)%len(OCR_NOISE)],
                         '课 堂 记 录 l / O 识别残片', f'{clock(timestamp)} 播放 暂停 1.0x']
                ocr.append(dict(timestampMs=timestamp, texts=lines, frameRef=f'frames/{media}/{timestamp}.jpg'))
        dump(folder/'ingest-asr.json', asr)
        dump(folder/'ingest-ocr.json', ocr)
        (folder/'asr.txt').write_text('\n'.join(f'[{clock(s["startMs"])} --> {clock(s["endMs"])}] {s["text"]}' for s in asr)+'\n', encoding='utf-8')
        (folder/'ocr.txt').write_text('\n\n'.join(f'[{clock(f["timestampMs"])}] '+ '\n'.join(f['texts']) for f in ocr)+'\n', encoding='utf-8')
        # Hash depends on actual ingest bytes; source edits invalidate derived chunk IDs.
        digest = hashlib.sha256((folder/'ingest-asr.json').read_bytes()+(folder/'ingest-ocr.json').read_bytes()).hexdigest()
        # Half hard negatives (same topic, unavailable details), half off-topic negatives.
        hard = i%4 in (0, 1)
        third = negative if hard else '换个话题，'+OFF_TOPIC[(i//4)*2+i%2]
        questions = [dict(id=f'{name}-q{j+1}', turn=j+1, userQuestion=q,
                          standaloneQuery=standalone)
                     for j, (q, standalone) in enumerate([
                         (q1, title+'：'+q1), (q2, title+'：'+q2.removeprefix('那')),
                         (third, title+'：'+third if hard else third)])]
        videos.append(dict(id=name, title=title, durationMs=1200000, mediaId=media,
                           userId=user, contentHash=digest, questions=questions))
        for j in range(3):
            annotations.append(dict(questionId=questions[j]['id'], videoId=name,
                split='calibration' if i%2 == 0 else 'holdout', related=j<2,
                category='answerable' if j<2 else ('hard-negative' if hard else 'off-topic'),
                supportIntervals=[dict(startMs=ordered_sections.index(sections[j])*300000,
                                       endMs=(ordered_sections.index(sections[j])+1)*300000)] if j<2 else [],
                reason=sections[j] if j<2 else ('视频没有给出所问具体信息；主题相近不等于可回答。' if hard else '视频未涉及这个跨主题问题。')))
        counts.append(dict(videoId=name, asrCharacters=sum(len(s['text']) for s in asr),
                           asrSegments=len(asr), ocrFrames=len(ocr),
                           ocrCharacters=sum(len(t) for f in ocr for t in f['texts'])))
    dump(ROOT/'manifest.json', dict(schemaVersion=1, provenance='synthetic-authored-v1', videos=videos))
    dump(ROOT/'evaluator/annotations.json', annotations)
    dump(ROOT/'dataset-counts.json', counts)
    print(json.dumps(dict(videos=len(videos), questions=len(annotations),
        asrCharacters=sum(c['asrCharacters'] for c in counts),
        ocrCharacters=sum(c['ocrCharacters'] for c in counts)), ensure_ascii=False))

if __name__ == '__main__':
    main()
